import json
import logging
from pydantic import BaseModel, Field
from google import genai
from google.genai import types
from app.config import settings
from app.schemas.interview import InterviewReportAIOutput
from app.services.pdf_service import generate_pdf_from_html

logger = logging.getLogger(__name__)

class ResumeHtmlOutput(BaseModel):
    html: str = Field(description="The HTML content of the resume styled and formatted for printing to PDF")

def get_genai_client() -> genai.Client:
    """Initialize and return Google GenAI client."""
    if not settings.GOOGLE_GENAI_API_KEY or "your_gemini_api_key" in settings.GOOGLE_GENAI_API_KEY:
        raise ValueError(
            "GOOGLE_GENAI_API_KEY is not configured or still has placeholder value in .env. "
            "Please obtain an API key from Google AI Studio (https://aistudio.google.com/) and update your .env file."
        )
    return genai.Client(api_key=settings.GOOGLE_GENAI_API_KEY)

def clean_json_response(raw_text: str) -> dict:
    """Helper to extract and parse JSON from model output."""
    cleaned = raw_text.strip()
    if cleaned.startswith("```json"):
        cleaned = cleaned[7:]
    elif cleaned.startswith("```"):
        cleaned = cleaned[3:]
    if cleaned.endswith("```"):
        cleaned = cleaned[:-3]
    return json.loads(cleaned.strip())

async def generate_interview_report(resume: str | None, self_description: str | None, job_description: str) -> dict:
    """
    Call Gemini model to generate a structured interview preparation report.
    """
    client = get_genai_client()

    prompt = f"""Generate an interview report for a candidate with the following details:
Resume: {resume or 'N/A'}
Self Description: {self_description or 'N/A'}
Job Description: {job_description}
"""

    response = client.models.generate_content(
        model=settings.GEMINI_MODEL,
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
            response_schema=InterviewReportAIOutput,
        )
    )

    if not response.text:
        raise ValueError("Empty response received from Gemini model.")

    return clean_json_response(response.text)

async def generate_resume_pdf(resume: str | None, self_description: str | None, job_description: str) -> bytes:
    """
    Call Gemini model to tailor resume HTML and convert to PDF via Playwright.
    """
    client = get_genai_client()

    prompt = f"""Generate resume for a candidate with the following details:
Resume: {resume or 'N/A'}
Self Description: {self_description or 'N/A'}
Job Description: {job_description}

the response should be a JSON object with a single field "html" which contains the HTML content of the resume which can be converted to PDF using any library like puppeteer.
The resume should be tailored for the given job description and should highlight the candidate's strengths and relevant experience. The HTML content should be well-formatted and structured, making it easy to read and visually appealing.
The content of resume should be not sound like it's generated by AI and should be as close as possible to a real human-written resume.
you can highlight the content using some colors or different font styles but the overall design should be simple and professional.
The content should be ATS friendly, i.e. it should be easily parsable by ATS systems without losing important information.
The resume should not be so lengthy, it should ideally be 1-2 pages long when converted to PDF. Focus on quality rather than quantity and make sure to include all the relevant information that can increase the candidate's chances of getting an interview call for the given job description.
"""

    response = client.models.generate_content(
        model=settings.GEMINI_MODEL,
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
            response_schema=ResumeHtmlOutput,
        )
    )

    if not response.text:
        raise ValueError("Empty response received from Gemini model for resume generation.")

    json_content = clean_json_response(response.text)
    html_content = json_content.get("html", "")

    if not html_content:
        raise ValueError("Model failed to generate resume HTML content.")

    pdf_bytes = await generate_pdf_from_html(html_content)
    return pdf_bytes
